import { LikeC4 } from "likec4";
import { existsSync, readFileSync } from "node:fs";
import { realpath } from "node:fs/promises";
import { join, relative } from "node:path";
import { Effect } from "effect";
import type { ActivityConfig } from "./activity";
import { io, failure } from "./effects";

export const acquireModel = (workspace: string) => Effect.acquireRelease(
  io("LikeC4.open", () => LikeC4.fromWorkspace(workspace, { logger: false, printErrors: false })),
  source => io("LikeC4.dispose", () => source.dispose()).pipe(Effect.orDie),
);

/**
 * Why a model does not compile, in words a person can act on: the parser's first errors with file and line, and, if there is one, an older pathlight
 * draft left in the workspace root (drafts now live in `.pathlight/`, and two copies define every element twice).
 */
export const invalidModel = (source: LikeC4, workspace: string) => {
  const errors = source.getErrors().slice(0, 3).map(error => `${relative(workspace, error.sourceFsPath)}:${error.line}: ${error.message.split("\n")[0]}`);
  const root = join(workspace, "pathlight.model.c4");
  const old = existsSync(root) && readFileSync(root, "utf8").startsWith("// Generated by `pathlight draft`");
  return `Invalid LikeC4 model${errors.length ? `: ${errors.join("; ")}` : ""}.`
    + (old ? " An older pathlight draft is in the workspace root (pathlight.model.c4, likec4.config.json, pathlight.activity.json); drafts now live in .pathlight/, so delete those three files." : "");
};

const viewRows = Effect.fn("Catalog.viewRows")(function* (workspace: string) {
  const directory = yield* io("Catalog.workspace", () => realpath(workspace));
  const source = yield* acquireModel(directory);
  if (source.hasErrors()) return yield* Effect.fail(failure("Catalog.validate", invalidModel(source, directory)));
  const views = [];
  for (const project of source.projects()) {
    const model = yield* io("LikeC4.compute", () => source.computedModel(project));
    // LikeC4 adds a "Landscape" index view when none is written; only written views have a source file.
    for (const view of model.views()) views.push({ project, id: view.id, title: view.title ?? view.id, written: Boolean(view.$view.sourcePath) });
  }
  return { workspace: directory, views };
}, Effect.scoped);

export const listViews = Effect.fn("Catalog.list")(function* (workspace: string) {
  const { workspace: directory, views } = yield* viewRows(workspace);
  return { workspace: directory, views: views.map(({ project, id, title }) => ({ project, id, title })) };
});

/** The view `open` shows when none is named: the written view called `index`, else the first written view, else any. */
export const overviewId = Effect.fn("Catalog.overview")(function* (workspace: string, project?: string) {
  const views = (yield* viewRows(workspace)).views.filter(view => !project || view.project === project);
  const written = views.filter(view => view.written);
  const chosen = written.find(view => view.id === "index") ?? written[0] ?? views[0];
  if (!chosen) return yield* Effect.fail(failure("Catalog.overview", "This workspace has no views. Run `pathlight setup` (or ask the agent: /pathlight) to draw a first one from the code."));
  return chosen.id;
});

export const selectView = Effect.fn("Catalog.select")(function* (workspace: string, id: string, project?: string) {
  const catalog = yield* listViews(workspace);
  const matches = catalog.views.filter(view => view.id === id && (!project || view.project === project));
  const view = matches[0];
  if (!view) return yield* Effect.fail(failure("Catalog.select", `Unknown view '${id}'. Run pathlight list --workspace ${workspace}.`));
  if (matches.length !== 1) return yield* Effect.fail(failure("Catalog.select", `View '${id}' exists in multiple projects. Specify --project.`));
  return { workspace: catalog.workspace, ...view };
});

export type View = Effect.Success<ReturnType<typeof selectView>>;

export const validateActivityMapping = Effect.fn("Catalog.validateMapping")(function* (view: View, config: ActivityConfig) {
  if (config.project !== view.project) return yield* Effect.fail(failure("Catalog.validateMapping", "Activity mapping project must match the selected diagram project."));
  const source = yield* acquireModel(view.workspace);
  const model = yield* io("LikeC4.compute", () => source.computedModel(view.project));
  const elements = new Set([...model.elements()].map(element => String(element.id)));
  for (const mapping of config.mappings) {
    if (!elements.has(mapping.element)) return yield* Effect.fail(failure("Catalog.validateMapping", `Unknown activity element '${mapping.element}'.`));
  }
}, Effect.scoped);
